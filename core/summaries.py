"""
core/summaries.py - the single-regulation AI summary (T029; FR-4.1, FR-4.2,
FR-4.7; DL-18 point 5, DL-19).

What goes in (build_facts): only what has been entered in Regulator - the
regulation's details and the SME's notes, each Business Unit's status and
explanation, the latest notes from its activity, and the uploaded documents
(read by core/doc_reader.py). No outside knowledge, no internet.

What comes out (parse_output): the approved format from the example
summaries doc (approved Nov 10):
  short             at most 3 lines, shown first, with "More"
  regulation        part 1 - what it requires and by when
  documentsAndNotes part 2 - what the documents and notes add
  units             part 3 - one line per Business Unit, explaining its status
  actionsNeeded     part 4 - only actions stated in the inputs

Rules kept by code, not left to the AI:
  - Each unit's colour and status name ("red (Action needed)") come from the
    stored status, never from the AI (FR-2.1: status is set by people).
  - Contacts are the Users assigned to that unit (DL-8), added by the server
    when the summary is shown - the AI never writes a name or an address.
  - Documents that could not be read are named by the server.
  - The fingerprint covers every input, the model and the prompt version:
    the same inputs give the same stored summary on the Roadmap and the
    Dashboard, and any change regenerates it the next time it is opened.

Pure functions only (no Firestore, Storage or Gemini), so tests need nothing.
"""
from __future__ import annotations

import hashlib
import json
import re
from datetime import datetime, timezone

PROMPT_VERSION = "t029-2"

DISCLAIMER = ("Generated by AI from information entered in Regulator. Review before using it. "
              "Material is for general information only and does not constitute professional or legal advice.")

# status -> (colour word, status name). None = not set.
STATUS_WORDS = {
    "action_needed": ("red", "Action needed"),
    "pending": ("amber", "Pending"),
    "compliant": ("green", "Compliant"),
}
STATUS_ORDER = {"action_needed": 0, "pending": 1, None: 2, "compliant": 3}

MAX_NOTES_PER_UNIT = 5
MAX_NOTE_CHARS = 1000
MAX_DOCS = 8

LIMITS = {"short": 500, "regulation": 1500, "documentsAndNotes": 1500, "unit": 600, "action": 600}


def status_label(status) -> str:
    if status in STATUS_WORDS:
        colour, name = STATUS_WORDS[status]
        return f"{colour} ({name})"
    return "Not set"


def _iso_day(value) -> str:
    if isinstance(value, datetime):
        return value.astimezone(timezone.utc).strftime("%Y-%m-%d") if value.tzinfo else value.strftime("%Y-%m-%d")
    if isinstance(value, str):
        return value[:10]
    return ""


def _when(value) -> str:
    """Sortable ISO text for any timestamp shape ('' sorts oldest)."""
    if isinstance(value, datetime):
        return (value if value.tzinfo else value.replace(tzinfo=timezone.utc)).isoformat()
    return value if isinstance(value, str) else ""


def build_facts(reg: dict, entries: list[dict], bu_labels: dict, people: dict) -> dict:
    """
    reg        the regulation with document `key` / `hidden` flags (with_document_flags)
    entries    its activity entries (each with `id`)
    bu_labels  unit code -> name
    people     uid -> {displayName, email}
    """
    statuses = reg.get("buStatuses") or {}
    units = []
    for code in reg.get("businessUnitIds") or []:
        cur = statuses.get(code) or {}
        status = cur.get("status") if cur.get("status") in STATUS_WORDS else None
        notes = sorted(
            (e for e in entries if e.get("buCode") == code and not e.get("removed") and (e.get("note") or "").strip()),
            key=lambda e: _when(e.get("at")), reverse=True,
        )[:MAX_NOTES_PER_UNIT]
        units.append({
            "code": code,
            "name": bu_labels.get(code) or code,
            "status": status,
            "statusLabel": status_label(status),
            "explanation": (cur.get("note") or "").strip()[:MAX_NOTE_CHARS],
            "recentNotes": [
                {"date": _iso_day(e.get("at")),
                 "by": (people.get(e.get("actorUid")) or {}).get("displayName") or "a former user",
                 "note": e["note"].strip()[:MAX_NOTE_CHARS]}
                for e in notes
            ],
        })
    names = {u["code"]: u["name"] for u in units}
    documents = [
        {"key": d["key"], "fileName": d.get("fileName") or "document",
         "scope": names.get(d.get("buCode"), d.get("buCode")) if d.get("buCode") else "Whole regulation"}
        for d in reg.get("documents") or [] if not d.get("hidden")
    ]
    return {
        "regulation": {
            "title": reg.get("title") or "",
            "abbreviatedTitle": reg.get("abbreviatedTitle") or "",
            "dueDate": reg.get("dueDate") or "",
            "domain": reg.get("domain") or "",
            "country": reg.get("country") or "",
            "region": reg.get("region") or "",
            "smeNotes": (reg.get("notes") or "").strip(),
        },
        "units": units,
        "documents": documents,
    }


def fingerprint(facts: dict, model: str) -> str:
    raw = json.dumps({"v": PROMPT_VERSION, "model": model, "facts": facts}, sort_keys=True, default=str)
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


SYSTEM_PROMPT = """You write compliance summaries for Regulator, a tool that company sustainability teams use to track regulations.
Write for a busy executive: plain English, short sentences, no jargon, no legal advice.

Rules:
1. Use ONLY the information provided: the regulation's details, the SME notes, each Business Unit's status, explanation and recent notes, and the attached documents. Do not use outside knowledge.
2. Never invent dates, citations, requirements, numbers, people or contact details.
3. Never set, change, suggest or predict a compliance status. Statuses are set by people and are given to you.
4. Whenever you mention a status colour, follow it with its status name in brackets: red (Action needed), amber (Pending), green (Compliant). A unit with no status is "Not set".
5. If something is missing, say so plainly (for example "No notes have been entered."). Do not fill gaps.
6. Never mention email addresses.
7. Refer to Business Units by their name (for example "Printers"), never by their code (for example "BU2"). Use the code only in the "code" fields of the JSON.

Return JSON only, with exactly these keys:
- "short": at most 3 short sentences (about 60 words): what the regulation requires and by when, then where the Business Units stand, red first.
- "regulation": 1 to 3 sentences: what the regulation requires and by when, from the inputs.
- "documentsAndNotes": 1 to 3 sentences: what the documents and notes add. If there are none, say so.
- "units": one object per Business Unit given, in the same order: {"code": the unit's code, "summary": one sentence explaining its status from its explanation and notes}.
- "actionsNeeded": a list of {"code": the unit's code, or "" for the whole regulation, "action": one sentence}. Only actions stated or clearly described in the inputs, with any dates given. Red (Action needed) units first. Do not suggest actions of your own. If none are entered, return an empty list.
All keys together should come to about 150 to 250 words."""


def user_parts(facts: dict, reads: list[dict]) -> list:
    """
    The request: the facts as JSON, then each document read.
    reads: [{fileName, scope, kind: "text"|"pdf", text?, data_b64?, partial}]
    """
    for_ai = {
        "regulation": facts["regulation"],
        "businessUnits": [
            {"code": u["code"], "name": u["name"], "status": u["statusLabel"],
             "explanation": u["explanation"] or "(none entered)", "recentNotes": u["recentNotes"]}
            for u in facts["units"]
        ],
    }
    parts = ["Summarise this regulation for the company.\n\nREGULATION DATA:\n" + json.dumps(for_ai, indent=1)]
    if not reads:
        parts.append("ATTACHED DOCUMENTS: none.")
    for r in reads:
        head = f"ATTACHED DOCUMENT: {r['fileName']} (for: {r['scope']})" + (" - only the first part is included" if r.get("partial") else "")
        if r["kind"] == "pdf":
            parts.append(head + " - the PDF follows.")
            parts.append({"inline_data": {"mime_type": "application/pdf", "data": r["data_b64"]}})
        else:
            parts.append(f"{head}\n---\n{r['text']}\n---")
    return parts


def _text(value, limit: int) -> str:
    if not isinstance(value, str):
        return ""
    value = " ".join(value.split())
    return value if len(value) <= limit else value[: limit - 1].rstrip() + "…"


_EMAIL = re.compile(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+")


def scrub(text: str, names: dict) -> str:
    """
    T033: two prompt rules also kept by code, on everything the AI writes.
    Email addresses are removed (contacts are added by the server), and any
    Business Unit code the AI used is replaced by the unit's name.
    """
    if not text:
        return text
    text = _EMAIL.sub("", text)
    for code, name in names.items():
        if code and name and code != name:
            text = re.sub(rf"(?<![\w-]){re.escape(code)}(?![\w-])", name, text)
    text = re.sub(r"\(\s*\)", "", text)
    text = " ".join(text.split())
    return re.sub(r"\s+([.,;:])", r"\1", text)


class InvalidSummary(ValueError):
    pass


def parse_output(data, facts: dict, not_read: list[dict]) -> dict:
    """
    Checks the AI's JSON and fixes it to the facts: units in the stored order,
    with stored status labels; unknown unit codes dropped; actions for red
    units first. Raises InvalidSummary if the answer is unusable.
    """
    if not isinstance(data, dict):
        raise InvalidSummary("answer is not an object")
    unit_names = {u["code"]: u["name"] for u in facts["units"]}
    short = scrub(_text(data.get("short"), LIMITS["short"]), unit_names)
    regulation = scrub(_text(data.get("regulation"), LIMITS["regulation"]), unit_names)
    if not short or not regulation:
        raise InvalidSummary("short or regulation missing")
    docs_notes = scrub(_text(data.get("documentsAndNotes"), LIMITS["documentsAndNotes"]), unit_names) or "No documents or notes have been added."
    if not_read:
        names = ", ".join(f"{d['fileName']} ({d['reason']})" for d in not_read)
        noun = "document" if len(not_read) == 1 else "documents"
        docs_notes += f" {len(not_read)} {noun} could not be read: {names}."

    by_code = {}
    for item in data.get("units") or []:
        if isinstance(item, dict) and isinstance(item.get("code"), str):
            by_code.setdefault(item["code"], scrub(_text(item.get("summary"), LIMITS["unit"]), unit_names))
    units = [
        {"code": u["code"], "name": u["name"], "status": u["status"], "statusLabel": u["statusLabel"],
         "summary": by_code.get(u["code"]) or ("No explanation has been entered." if not u["explanation"] else "")}
        for u in facts["units"]
    ]
    units.sort(key=lambda u: STATUS_ORDER.get(u["status"], 2))

    known = {u["code"]: u for u in facts["units"]}
    actions = []
    for item in data.get("actionsNeeded") or []:
        if not isinstance(item, dict):
            continue
        code = item.get("code") if isinstance(item.get("code"), str) else ""
        if code and code not in known:
            code = ""
        action = scrub(_text(item.get("action"), LIMITS["action"]), unit_names)
        if action:
            actions.append({"code": code, "unit": known[code]["name"] if code else "", "action": action})
    actions.sort(key=lambda a: STATUS_ORDER.get(known[a["code"]]["status"], 2) if a["code"] else 1)

    return {"short": short, "regulation": regulation, "documentsAndNotes": docs_notes,
            "units": units, "actionsNeeded": actions}


def contacts_by_unit(users: dict, unit_codes: list[str]) -> dict:
    """DL-8: the people to contact for a unit are the Users assigned to it."""
    out = {code: [] for code in unit_codes}
    for u in users.values():
        if u.get("hidden") or u.get("role") != "user":
            continue
        for code in u.get("businessUnitIds") or []:
            if code in out:
                out[code].append({"name": u.get("displayName") or u.get("email") or "", "email": u.get("email") or ""})
    for code in out:
        out[code].sort(key=lambda p: p["name"].lower())
    return out


def present(reg_id: str, stored: dict, contacts: dict, cached: bool) -> dict:
    """The API response: the stored summary plus live contacts and the labels."""
    summary = stored["summary"]
    generated = stored.get("generatedAt")
    return {
        "regulationId": reg_id,
        "aiGenerated": True,
        "disclaimer": DISCLAIMER,
        "generatedAt": generated.isoformat() if isinstance(generated, datetime) else generated,
        "model": stored.get("model", ""),
        "cached": cached,
        "short": summary["short"],
        "regulation": summary["regulation"],
        "documentsAndNotes": summary["documentsAndNotes"],
        "units": [{**u, "contacts": contacts.get(u["code"], [])} for u in summary["units"]],
        "actionsNeeded": summary["actionsNeeded"],
        "documents": stored.get("documents") or {"read": [], "partlyRead": [], "notRead": []},
    }
